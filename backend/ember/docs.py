"""Render reference documentation from the curated evidence so docs never drift from data.

    python -m ember.docs   # writes docs/SOURCES.md, docs/FINDINGS_CATALOG.md, docs/DATA_GAPS.md
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "data" / "build" / "evidence_bundle.json"
DOCS = ROOT / "docs"

HEADER = "<!-- Generated by `python -m ember.docs` from data/curated/*.json. Do not edit by hand. -->\n\n"


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def main():
    b = json.loads(BUILD.read_text())
    DOCS.mkdir(exist_ok=True)

    lines = [HEADER, "# Sources\n\n", "Every document the evidence service cites, with what was actually read.\n\n",
             "| ID | Source | Type | Access | Note |\n| --- | --- | --- | --- | --- |\n"]
    for s in b["sources"]:
        lines.append(f"| {s['id']} | [{_cell(s['title'])}]({s['url']}), {_cell(s['authors'])} ({s['year']}), {_cell(s['identifier'])} | "
                     f"{_cell(s['document_type'])} | {s['access']} | {_cell(s['access_note'])} |\n")
    (DOCS / "SOURCES.md").write_text("".join(lines))

    lines = [HEADER, "# Findings catalog\n\n",
             f"{len(b['findings'])} findings. Evidence types: verified measurement (checked against NASA tables and PSI-25), "
             "author conclusion (stated by NASA authors), hypothesis (proposed, not established).\n\n"]
    studies = {s["id"]: s for s in b["studies"]}
    for sid in [s["id"] for s in b["studies"]]:
        fs = [f for f in b["findings"] if f["study_id"] == sid]
        if not fs:
            continue
        st = studies[sid]
        lines.append(f"## {st['name']} ({sid})\n\nIndependence from BASS-II: `{st['independence_from_bass2']}`. Lineage: {st['lineage_group']}.\n\n")
        for f in fs:
            refs = "; ".join(f"{r['source_id']} ({r['locator']})" for r in f["source_refs"])
            lines.append(f"### {f['id']} — {f['title']}\n\n- **Evidence type:** {f['evidence_type_label']}. {f['evidence_basis']}\n"
                         f"- **Question:** {f['research_question']}\n- **Finding:** {f['statement']}\n"
                         f"- **Material / geometry:** {f['material']}; {f['geometry']}\n"
                         f"- **Conditions:** " + "; ".join(f"{k} {v}" for k, v in f["conditions"].items()) + "\n"
                         f"- **Limitations:** " + " ".join(f["limitations"]) + "\n"
                         f"- **Sources:** {refs}\n\n")
    (DOCS / "FINDINGS_CATALOG.md").write_text("".join(lines))

    lines = [HEADER, "# Unresolved data gaps\n\n", "| ID | Status | Priority | Study | Gap | Detail | Path to resolution |\n| --- | --- | --- | --- | --- | --- | --- |\n"]
    order = {"high": 0, "medium": 1, "low": 2}
    for g in sorted(b["gaps"], key=lambda g: (g["status"] == "resolved", order[g["priority"]], g["id"])):
        lines.append(f"| {g['id']} | {g['status']} | {g['priority']} | {g['study_id']} | {_cell(g['title'])} | {_cell(g['detail'])} | {_cell(g['resolution_path'])} |\n")
    (DOCS / "DATA_GAPS.md").write_text("".join(lines))
    print("wrote docs/SOURCES.md, docs/FINDINGS_CATALOG.md, docs/DATA_GAPS.md")


if __name__ == "__main__":
    main()
